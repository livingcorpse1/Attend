-- =====================================================================================
-- VeriQra baseline schema.
--
-- Storage rules for the whole application:
--   * every timestamp column is timezone aware and holds UTC;
--   * every identifier is a database generated identity;
--   * constraints that protect an attendance decision live in the database, not only
--     in the service layer, so that a bug cannot produce two records for one student.
-- =====================================================================================

-- ------------------------------------------------------------------ accounts
create table app_user (
    id               bigint generated by default as identity primary key,
    email            varchar(190) not null unique,
    password_hash    varchar(100) not null,
    full_name        varchar(140) not null,
    role             varchar(20)  not null,
    active           boolean      not null default true,
    student_number   varchar(40),
    face_state       varchar(24)  not null default 'PENDING',
    face_verified_at timestamp with time zone,
    created_at       timestamp with time zone not null default current_timestamp,
    last_login_at    timestamp with time zone,
    constraint ck_app_user_role check (role in ('ADMIN', 'FACULTY', 'STUDENT')),
    constraint ck_app_user_face_state check (face_state in ('PENDING', 'VERIFIED', 'REVOKED'))
);
create index ix_app_user_role on app_user(role);
create unique index ux_app_user_student_number on app_user(student_number);

-- ------------------------------------------------------------ academic structure
create table subject (
    id         bigint generated by default as identity primary key,
    code       varchar(30)  not null unique,
    name       varchar(140) not null,
    faculty_id bigint references app_user(id)
);

create table class_section (
    id         bigint generated by default as identity primary key,
    subject_id bigint      not null references subject(id),
    name       varchar(60) not null,
    room       varchar(80) not null,
    constraint ux_class_section_subject_name unique (subject_id, name)
);
create index ix_class_section_subject on class_section(subject_id);

create table enrollment (
    student_id  bigint not null references app_user(id),
    class_id    bigint not null references class_section(id),
    enrolled_at timestamp with time zone not null default current_timestamp,
    primary key (student_id, class_id)
);
create index ix_enrollment_class on enrollment(class_id);

create table timetable (
    id           bigint generated by default as identity primary key,
    class_id     bigint not null references class_section(id),
    faculty_id   bigint not null references app_user(id),
    day_of_week  int    not null,
    starts       time   not null,
    ends         time   not null,
    constraint ck_timetable_day check (day_of_week between 1 and 7),
    constraint ck_timetable_range check (ends > starts)
);
create index ix_timetable_faculty on timetable(faculty_id, day_of_week);
create index ix_timetable_class on timetable(class_id, day_of_week);

-- --------------------------------------------------------------------- attendance
create table attendance_session (
    id            bigint generated by default as identity primary key,
    class_id      bigint not null references class_section(id),
    faculty_id    bigint not null references app_user(id),
    started_at    timestamp with time zone not null,
    ends_at       timestamp with time zone not null,
    closed_at     timestamp with time zone,
    status        varchar(20) not null,
    session_nonce varchar(40) not null,
    title         varchar(160),
    version       bigint not null default 0,
    constraint ck_session_status check (status in ('ACTIVE', 'CLOSED', 'EXPIRED'))
);
create index ix_session_class on attendance_session(class_id, started_at);
create index ix_session_faculty on attendance_session(faculty_id, started_at);
create index ix_session_active on attendance_session(status, ends_at);

create table attendance_record (
    id             bigint generated by default as identity primary key,
    session_id     bigint not null references attendance_session(id),
    student_id     bigint not null references app_user(id),
    status         varchar(24) not null,
    recorded_at    timestamp with time zone not null,
    match_score    double precision,
    liveness_score double precision,
    method         varchar(32) not null,
    source         varchar(24) not null,
    note           varchar(240),
    constraint uq_attendance_student_session unique (session_id, student_id),
    constraint ck_attendance_status check (status in ('PRESENT', 'ABSENT', 'EXCUSED'))
);
create index ix_attendance_student on attendance_record(student_id, recorded_at);
create index ix_attendance_session_status on attendance_record(session_id, status);

-- ---------------------------------------------------------------- verification trail
create table verification_attempt (
    id           bigint generated by default as identity primary key,
    session_id   bigint references attendance_session(id),
    student_id   bigint not null references app_user(id),
    outcome      varchar(30) not null,
    detail       varchar(240),
    match_score  double precision,
    attempted_at timestamp with time zone not null default current_timestamp
);
create index ix_verification_attempt_student on verification_attempt(student_id, attempted_at);

-- --------------------------------------------------------------------- biometrics
create table face_template (
    student_id      bigint primary key references app_user(id),
    model_version  varchar(32) not null,
    embedding       bytea not null,
    enrolled_at     timestamp with time zone not null default current_timestamp,
    sample_count    int not null,
    quality_score   double precision not null,
    mean_similarity double precision not null,
    storage_path    varchar(240)
);

create table liveness_challenge (
    id          varchar(64) primary key,
    student_id  bigint not null references app_user(id),
    kind        varchar(24) not null,
    issued_at   timestamp with time zone not null,
    expires_at  timestamp with time zone not null,
    consumed_at timestamp with time zone,
    context     varchar(40)
);
create index ix_challenge_student on liveness_challenge(student_id, expires_at);

create table verification_ticket (
    id           varchar(64) primary key,
    student_id   bigint not null references app_user(id),
    session_id   bigint not null references attendance_session(id),
    challenge_id varchar(64) not null,
    issued_at    timestamp with time zone not null,
    expires_at   timestamp with time zone not null,
    consumed_at  timestamp with time zone,
    state        varchar(24) not null
);
create index ix_ticket_student on verification_ticket(student_id, expires_at);

-- --------------------------------------------------------- audit, throttle, settings
create table audit_log (
    id          bigint generated by default as identity primary key,
    actor_id    bigint not null references app_user(id),
    action      varchar(60)  not null,
    target      varchar(180) not null,
    reason_code varchar(60),
    explanation varchar(500),
    old_value   varchar(60),
    new_value   varchar(60),
    created_at  timestamp with time zone not null default current_timestamp
);
create index ix_audit_created on audit_log(created_at);
create index ix_audit_actor on audit_log(actor_id, created_at);

create table auth_attempt (
    id           bigint generated by default as identity primary key,
    identifier   varchar(190) not null,
    ip_address   varchar(64)  not null,
    outcome      varchar(24)  not null,
    attempted_at timestamp with time zone not null default current_timestamp
);
create index ix_auth_attempt_identifier on auth_attempt(identifier, attempted_at);
create index ix_auth_attempt_ip on auth_attempt(ip_address, attempted_at);

create table app_setting (
    setting_key   varchar(80) primary key,
    setting_value varchar(240) not null
);
